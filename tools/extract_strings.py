#!/usr/bin/env python3
"""Collects WinNCDU's translatable strings and checks translations.

    python -I tools/extract_strings.py            write res/lang/template.lang, check res/lang/*.lang
    python -I tools/extract_strings.py --check    only check (CI): the template lists exactly the
                                                  strings in the code, every TrF/TrN call passes as
                                                  many values as its text has {n}, and translations
                                                  use no {n} their English text lacks
    python -I tools/extract_strings.py --update res/lang/de.lang
                                                  bring a translation up to date: the template's
                                                  order, new strings added empty, strings the code
                                                  no longer has kept at the end as comments
    python -I tools/extract_strings.py --new de --name Deutsch
                                                  start res/lang/de.lang from the template

Strings are the first arguments of Tr(L"..."), TrF(L"...", ...) and N_(L"..."), the second and
third of TrN(n, L"one", L"other", ...) in src/, plus name = and desc = in res/cleaners.ini.
Exit code 1 when a check fails.
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
LANG = os.path.join(ROOT, "res", "lang")
TEMPLATE = os.path.join(LANG, "template.lang")
CLEANERS = os.path.join(ROOT, "res", "cleaners.ini")

PLURAL_SEP = "\x1f"
FUNCS = {"Tr", "TrF", "TrN", "N_"}

HEADER = """\
# WinNCDU translation template. Generated by tools/extract_strings.py from the code: don't edit
# this file; copy it to <code>.lang (python -I tools/extract_strings.py --new <code> --name <Name>).
#
# One string per line:   English text = your translation
#   - Leave the right side empty for strings you haven't translated: WinNCDU shows the English.
#   - Keep {0}, {1}, ... : they are values (sizes, names, counts). Move them where your language
#     needs them; leave one out only if the sentence really doesn't need it.
#   - Plural lines look like  {0} item|{0} items = ...  Give the forms your language's plural rule
#     (@plural below) has, separated by |, e.g. for German  {0} Element|{0} Elemente
#   - \\n is a new line, \\s a space at the start or end, \\= \\| \\# \\@ \\\\ the character itself.
#   - Lines starting with # are comments (the source of each string, for context).
#   - Menu text: && is a single "&"; text after \\t is the keyboard shortcut.
# Test it without building: put the file in a "lang" folder next to winncdu.exe, restart
# WinNCDU, and pick it in Menu > Language. Problems in the file show up as a message there.
#
# @name: the language's own name, e.g. Deutsch.
# @plural: one (1 | other: English, German, Spanish, ...), zero-one (0, 1 | other: French),
#   none (Japanese, Chinese, ...), east-slavic, polish, czech, romanian, lithuanian, slovenian,
#   arabic. Leave it empty to use the usual rule for the file's language code.
# @translators: your name(s), optional.
@name =
@plural =
@translators =
"""

# ---------------------------------------------------------------------------------------------
# C++ scanning


def unescape_cpp(body):
    """The value of a C++ string literal's body."""
    out = []
    i = 0
    simple = {"n": "\n", "t": "\t", "r": "\r", "0": "\0", "\\": "\\", '"': '"', "'": "'", "a": "\a", "b": "\b",
              "f": "\f", "v": "\v", "?": "?"}
    while i < len(body):
        c = body[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        n = body[i + 1]
        if n == "x":
            j = i + 2
            while j < len(body) and body[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(chr(int(body[i + 2:j], 16)))
            i = j
        elif n == "u":
            out.append(chr(int(body[i + 2:i + 6], 16)))
            i += 6
        elif n == "U":
            out.append(chr(int(body[i + 2:i + 10], 16)))
            i += 10
        elif n in "01234567":
            j = i + 1
            while j < len(body) and j < i + 4 and body[j] in "01234567":
                j += 1
            out.append(chr(int(body[i + 1:j], 8)))
            i = j
        else:
            out.append(simple.get(n, n))
            i += 2
    return "".join(out)


TOKEN = re.compile(
    r"""
    (?P<ws>\s+)
  | (?P<lcomment>//[^\n]*)
  | (?P<bcomment>/\*.*?\*/)
  | (?P<raw>(?:L|u8|u|U)?R"(?P<delim>[^(\s]*)\((?P<rawbody>.*?)\)(?P=delim)")
  | (?P<str>(?P<prefix>L|u8|u|U)?"(?P<body>(?:[^"\\\n]|\\.)*)")
  | (?P<chr>(?:L|u8|u|U)?'(?:[^'\\\n]|\\.)*')
  | (?P<pp>\#[^\n]*(?:\\\n[^\n]*)*)
  | (?P<ident>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<num>\.?[0-9](?:[0-9A-Za-z_.']|[eEpP][+-])*)
  | (?P<punct>::|->|.)
    """,
    re.S | re.X,
)


def tokenize(text):
    """(kind, value, line) tokens; comments, whitespace and preprocessor lines dropped."""
    line = 1
    pos = 0
    toks = []
    while pos < len(text):
        m = TOKEN.match(text, pos)
        kind = m.lastgroup
        s = m.group(0)
        if kind == "str" or kind == "raw" or kind == "delim" or kind == "body" or kind == "prefix" or kind == "rawbody":
            if m.group("raw"):
                toks.append(("str", m.group("rawbody"), line, True))
            else:
                toks.append(("str", unescape_cpp(m.group("body")), line, m.group("prefix") == "L"))
        elif kind in ("ws", "lcomment", "bcomment", "pp"):
            pass
        elif kind == "ident":
            toks.append(("ident", s, line, False))
        elif kind == "chr" or kind == "num":
            toks.append(("other", s, line, False))
        else:
            toks.append(("punct", s, line, False))
        line += s.count("\n")
        pos = m.end()
    return toks


def split_args(toks, start):
    """Arguments of a call whose "(" is toks[start]: lists of tokens, and the index after ")"."""
    depth = 0
    args = [[]]
    i = start
    while i < len(toks):
        kind, v = toks[i][0], toks[i][1]
        if kind == "punct" and v in "([{":
            depth += 1
            if depth > 1:
                args[-1].append(toks[i])
        elif kind == "punct" and v in ")]}":
            depth -= 1
            if depth == 0:
                return args, i + 1
            args[-1].append(toks[i])
        elif kind == "punct" and v == "," and depth == 1:
            args.append([])
        else:
            args[-1].append(toks[i])
        i += 1
    return args, i


def literal(arg):
    """The text of an argument made of adjacent L"..." literals only, else None."""
    if not arg or any(t[0] != "str" or not t[3] for t in arg):
        return None
    return "".join(t[1] for t in arg)


PLACEHOLDER = re.compile(r"(?<!\{)\{([0-9])\}")


def placeholders(s):
    s = s.replace("{{", "")
    return {int(x) for x in PLACEHOLDER.findall(s)}


def scan_sources():
    """{key: [locations]} and a list of problems in calls."""
    found = {}
    problems = []
    for dirpath, _, files in os.walk(SRC):
        for name in sorted(files):
            if not name.endswith((".cpp", ".h")):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, ROOT).replace("\\", "/")
            with open(path, encoding="utf-8-sig") as f:
                toks = tokenize(f.read())
            for i, t in enumerate(toks):
                if t[0] != "ident" or t[1] not in FUNCS or i + 1 >= len(toks) or toks[i + 1][1] != "(":
                    continue
                if i > 0 and toks[i - 1][1] in (".", "->"):
                    continue  # a member of something else
                args, _ = split_args(toks, i + 1)
                where = "%s:%d" % (rel, t[2])
                if t[1] == "TrN":
                    if len(args) < 3:
                        continue
                    one, other = literal(args[1]), literal(args[2])
                    if one is None or other is None:
                        continue
                    key = one + PLURAL_SEP + other
                    used = placeholders(one) | placeholders(other)
                    given = len(args) - 2  # n is {0}
                else:
                    key = literal(args[0])
                    if key is None:
                        continue
                    used = placeholders(key)
                    given = len(args) - 1 if t[1] == "TrF" else 0
                if t[1] in ("TrF", "TrN"):
                    need = max(used) + 1 if used else 0
                    if need != given:
                        problems.append("%s: %s(\"%s\") uses %d value(s) but gets %d" % (where, t[1], key.split(PLURAL_SEP)[0][:60], need, given))
                elif used and t[1] == "Tr":
                    problems.append("%s: Tr(\"%s\") has {n} placeholders: use TrF" % (where, key[:60]))
                found.setdefault(key, []).append(where)
    # Cleanup categories: their names and descriptions are shown translated.
    if os.path.exists(CLEANERS):
        with open(CLEANERS, encoding="utf-8-sig") as f:
            for n, line in enumerate(f, 1):
                m = re.match(r"\s*(name|desc)\s*=\s*(.*?)\s*$", line)
                if m and m.group(2):
                    found.setdefault(m.group(2), []).append("res/cleaners.ini:%d" % n)
    return found, problems


# ---------------------------------------------------------------------------------------------
# Language files


def escape(s):
    out = []
    for i, c in enumerate(s):
        if c == "\\":
            out.append("\\\\")
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "=":
            out.append("\\=")
        elif c == "|":
            out.append("\\|")
        elif c == " " and (i == 0 or i == len(s) - 1):
            out.append("\\s")
        elif c in "#@" and i == 0:
            out.append("\\" + c)
        else:
            out.append(c)
    return "".join(out)


def escape_key(key):
    return "|".join(escape(p) for p in key.split(PLURAL_SEP))


def find_unescaped(s, ch, start=0):
    i = start
    while i < len(s):
        if s[i] == "\\":
            i += 2
            continue
        if s[i] == ch:
            return i
        i += 1
    return -1


def split_unescaped(s, ch):
    parts, start = [], 0
    while True:
        p = find_unescaped(s, ch, start)
        if p < 0:
            parts.append(s[start:])
            return parts
        parts.append(s[start:p])
        start = p + 1


def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c != "\\" or i + 1 >= len(s):
            out.append(c)
            i += 1
            continue
        n = s[i + 1]
        out.append({"n": "\n", "t": "\t", "s": " "}.get(n, n if n in "\\=|#@" else "\\" + n))
        i += 2
    return "".join(out)


def read_lang(path):
    """(metadata lines, {key: value-as-written}, problems)."""
    meta, entries, problems = [], {}, []
    with open(path, encoding="utf-8-sig") as f:
        for n, raw in enumerate(f, 1):
            line = raw.strip(" \t\r\n")
            if not line or line.startswith("#"):
                continue
            eq = find_unescaped(line, "=")
            if eq < 0:
                problems.append("%s:%d: no \"=\"" % (os.path.basename(path), n))
                continue
            k, v = line[:eq].strip(" \t"), line[eq + 1:].strip(" \t")
            if k.startswith("@"):
                meta.append((k, v))
                continue
            parts = split_unescaped(k, "|")
            key = PLURAL_SEP.join(unescape(p) for p in parts)
            entries[key] = (v, n)
    return meta, entries, problems


def check_translation(path, keys):
    """Placeholder problems (errors) and notes (warnings, strings the code no longer has)."""
    errors, notes = [], []
    meta, entries, problems = read_lang(path)
    errors += problems
    base = os.path.basename(path)
    for key, (v, n) in entries.items():
        if key not in keys:
            notes.append("%s:%d: \"%s\" is no longer in the code" % (base, n, key.split(PLURAL_SEP)[0][:60]))
        if not v:
            continue
        forms = split_unescaped(v, "|") if PLURAL_SEP in key else [v]
        english = set()
        for p in key.split(PLURAL_SEP):
            english |= placeholders(p)
        for f in forms:
            ph = placeholders(unescape(f))
            extra = ph - english
            if extra:
                errors.append("%s:%d: {%s} is not in the English text" % (base, n, "}, {".join(str(x) for x in sorted(extra))))
            if PLURAL_SEP not in key and english - ph:
                notes.append("%s:%d: leaves out {%s}" % (base, n, "}, {".join(str(x) for x in sorted(english - ph))))
    return errors, notes


def sort_key(k):
    return (k.casefold(), k)


def template_text(found):
    lines = [HEADER]
    for key in sorted(found, key=sort_key):
        locs = found[key]
        shown = ", ".join(locs[:4]) + (" (+%d more)" % (len(locs) - 4) if len(locs) > 4 else "")
        lines.append("\n# %s\n%s =\n" % (shown, escape_key(key)))
    return "".join(lines)


def template_keys(path):
    if not os.path.exists(path):
        return set()
    return set(read_lang(path)[1].keys())


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def update_translation(path, found):
    meta, entries, _ = read_lang(path)
    have_meta = {k.lower() for k, _ in meta}
    head = HEADER.split("\n", 2)[2].split("@name =")[0]  # without the two lines about the template
    out = ["# WinNCDU translation. Kept in the template's order by tools/extract_strings.py --update\n"
           "# (new strings are added empty, strings the code no longer has move to the end).\n" + head]
    for k, v in meta:
        out.append("%s = %s\n" % (k, v))
    for m in ("@name", "@plural", "@translators"):
        if m not in have_meta:
            out.append("%s =\n" % m)
    for key in sorted(found, key=sort_key):
        locs = found[key]
        shown = ", ".join(locs[:4]) + (" (+%d more)" % (len(locs) - 4) if len(locs) > 4 else "")
        v = entries.get(key, ("", 0))[0]
        out.append("\n# %s\n%s =%s\n" % (shown, escape_key(key), " " + v if v else ""))
    stale = [k for k in entries if k not in found]
    if stale:
        out.append("\n# ---- No longer in the code (kept for reference; delete when done):\n")
        for k in sorted(stale, key=sort_key):
            out.append("# %s = %s\n" % (escape_key(k), entries[k][0]))
    write(path, "".join(out))
    return len([k for k in found if not entries.get(k, ("", 0))[0]]), len(stale)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="check only; don't write the template")
    ap.add_argument("--update", metavar="FILE", help="bring a translation up to date")
    ap.add_argument("--new", metavar="CODE", help="start res/lang/CODE.lang")
    ap.add_argument("--name", default="", help="with --new: the language's own name")
    ap.add_argument("--verbose", action="store_true")
    a = ap.parse_args()

    found, problems = scan_sources()
    ok = True
    for p in problems:
        print("error: " + p)
        ok = False

    if a.new:
        path = os.path.join(LANG, a.new + ".lang")
        if os.path.exists(path):
            sys.exit("%s exists already: use --update" % path)
        write(path, "@name = %s\n@plural =\n@translators =\n" % a.name)
        update_translation(path, found)
        print("wrote %s (%d strings)" % (os.path.relpath(path, ROOT), len(found)))
        return 0 if ok else 1
    if a.update:
        missing, stale = update_translation(a.update, found)
        print("updated %s: %d of %d strings to translate, %d no longer used" % (a.update, missing, len(found), stale))

    if a.check:
        have = template_keys(TEMPLATE)
        new, gone = set(found) - have, have - set(found)
        for k in sorted(new, key=sort_key):
            print("error: not in template.lang yet: \"%s\" (%s)" % (k.split(PLURAL_SEP)[0][:70], found[k][0]))
        for k in sorted(gone, key=sort_key):
            print("error: template.lang has a string the code no longer has: \"%s\"" % k.split(PLURAL_SEP)[0][:70])
        if new or gone:
            print("run: python -I tools/extract_strings.py")
            ok = False
    else:
        write(TEMPLATE, template_text(found))
        print("wrote res/lang/template.lang: %d strings" % len(found))

    for name in sorted(os.listdir(LANG)) if os.path.isdir(LANG) else []:
        if not name.endswith(".lang") or name == "template.lang":
            continue
        errors, notes = check_translation(os.path.join(LANG, name), set(found))
        for e in errors:
            print("error: " + e)
            ok = False
        for n in notes if a.verbose else notes[:20]:
            print("note: " + n)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
